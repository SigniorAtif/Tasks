import tailwindcss from '@tailwindcss/vite';
import { tanstackRouter } from '@tanstack/router-plugin/vite';
import react from '@vitejs/plugin-react';
import { defineConfig } from 'vite';
import { VitePWA } from 'vite-plugin-pwa';

// The brand colour (the logo's tile). Android tints the status bar with it.
const themeColor = '#4338ca';

// Where the dev server forwards API calls. The real API listens on 3000; point
// this somewhere else (a mock, another port) with API_PROXY_TARGET. `||`, not
// `??`, so an empty value counts as unset, like every other variable in .env.
const apiTarget = process.env.API_PROXY_TARGET || 'http://127.0.0.1:3000';

// The browser only ever talks to Vite's origin (http://localhost:5173). Vite
// forwards these paths to the API, so the session cookie is first-party and
// there's no CORS, exactly like production where one server serves both.
// `changeOrigin: false` keeps the browser's Host header, so Better Auth's
// origin checks see localhost:5173, the same origin as BETTER_AUTH_URL.
const proxy = {
  '/api': { target: apiTarget, changeOrigin: false },
  '/healthz': { target: apiTarget, changeOrigin: false },
};

export default defineConfig({
  plugins: [
    // Reads src/routes/ and writes src/routeTree.gen.ts on every dev start,
    // file change and build. It must run before the React plugin.
    tanstackRouter({
      target: 'react',
      // Match the repo's import style: name the file with its extension.
      addExtensions: true,
      quoteStyle: 'single',
    }),
    react(),
    tailwindcss(),
    // Makes the build an installable app: writes manifest.webmanifest (name,
    // icons, colours) and a service worker, sw.js, generated by Workbox.
    VitePWA({
      // A new deploy's service worker takes over as soon as it has installed
      // and the page reloads once, so "merge a PR" reaches the installed app
      // the next time it's opened, with no "update available" prompt.
      registerType: 'autoUpdate',
      // src/lib/pwa.ts registers it, so the plugin shouldn't add a <script>.
      injectRegister: false,
      manifest: {
        id: '/',
        name: 'Tasks',
        short_name: 'Tasks',
        description: 'Your week and your to-dos, in one place.',
        start_url: '/',
        scope: '/',
        // Opens in its own window with no browser address bar.
        display: 'standalone',
        theme_color: themeColor,
        // The splash screen behind the icon while the app starts (slate-50,
        // the page background).
        background_color: '#f8fafc',
        // Generated from public/logo.svg by `pnpm generate-pwa-assets`.
        icons: [
          { src: 'pwa-64x64.png', sizes: '64x64', type: 'image/png' },
          { src: 'pwa-192x192.png', sizes: '192x192', type: 'image/png' },
          { src: 'pwa-512x512.png', sizes: '512x512', type: 'image/png' },
          {
            src: 'maskable-icon-512x512.png',
            sizes: '512x512',
            type: 'image/png',
            purpose: 'maskable',
          },
        ],
      },
      workbox: {
        // Precache the app shell only: the built HTML, JS, CSS and icons.
        // Opening the app offline then still draws a screen (D-048).
        globPatterns: ['**/*.{html,js,css,svg,png,ico}'],
        // A navigation to any app URL (/login, a future /calendar) gets the
        // cached index.html, and the router takes it from there...
        navigateFallback: 'index.html',
        // ...except the server's own URLs. Google's sign-in redirect lands on
        // /api/auth/callback/google, which must reach the API, not the shell.
        navigateFallbackDenylist: [/^\/api\//, /^\/healthz/],
        // A new service worker activates as soon as it has installed instead
        // of waiting for every window of the app to close (skipWaiting), and
        // takes control of the open page right away (clientsClaim). That's
        // what 'autoUpdate' means; the plugin only turns these on by itself
        // when it injects the registration, which we do ourselves.
        skipWaiting: true,
        clientsClaim: true,
        // No runtimeCaching: API answers are never stored by the service
        // worker. TanStack Query is the one cache of API data (D-046).
      },
      // No service worker under `pnpm dev`: a cached shell there makes code
      // changes look like they didn't apply. Check the PWA with build + preview.
      devOptions: { enabled: false },
    }),
  ],
  server: {
    port: 5173,
    // Fail loudly if 5173 is taken instead of quietly moving to 5174: the
    // API's BETTER_AUTH_URL and the Google redirect URI both name 5173.
    strictPort: true,
    proxy,
  },
  // `vite preview` serves the production build; it needs the same forwarding.
  preview: { proxy },
});
