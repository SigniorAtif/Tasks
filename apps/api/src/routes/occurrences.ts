// `PATCH /api/v1/occurrences/:seriesId/:originalDate`: cancel one occurrence
// with a reason, change the reason, or restore it. The answer is the
// occurrence as the engine now computes it, so the PWA can put it straight
// into its cached calendar windows without fetching them again.
//
// The same body twice leaves the same state and gets the same answer, so a
// retry on bad Wi-Fi is harmless (D-042).

import { isoDateSchema, paths, updateOccurrenceSchema } from '@tasks/core';
import type { Hono } from 'hono';
import { changeOccurrence } from '../calendar/occurrences.ts';
import type { AppEnv } from '../http/context.ts';
import { jsonBody } from '../http/json-body.ts';
import { noSuchRow, rowId } from '../http/row-id.ts';

export function occurrenceRoutes(app: Hono<AppEnv>): void {
  app.patch(`${paths.occurrences}/:seriesId/:originalDate`, async (c) => {
    const seriesId = rowId(c.req.param('seriesId'), 'occurrence');
    // A date that isn't one can't be generated by any series: the same 404.
    const originalDate = c.req.param('originalDate');
    if (!isoDateSchema.safeParse(originalDate).success) throw noSuchRow('occurrence');
    const change = await jsonBody(c, updateOccurrenceSchema);

    const occurrence = await c.var.asUser((scope) =>
      changeOccurrence(scope, seriesId, originalDate, change),
    );
    if (!occurrence) throw noSuchRow('occurrence');
    return c.json(occurrence);
  });
}
